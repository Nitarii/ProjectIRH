import assert from 'node:assert/strict';
import {createResourceLifecycle,resourceId,RESPAWN_MINUTES} from '../src/resource-life.js';
let now=1_750_000_000_000;
const state={exhausted:{}},life=createResourceLifecycle(state,{now:()=>now});
const tree={type:0,x:34.6,z:12.4,max:40,hp:40,dead:false,mesh:{visible:true}};
life.spawn(tree);tree.hp=25;life.hit(tree);
now+=43000;
life.update([tree],()=>true);
assert.ok(tree.hp>25&&tree.hp<40,'damaged nodes must replenish slowly');
now+=180000;life.update([tree],()=>true);
assert.equal(tree.hp,40,'surviving node must recover completely');
life.deplete(tree);
assert.equal(tree.hp,0);assert.equal(tree.dead,true);
const until=state.exhausted[resourceId(tree)];
assert.ok(until-now>=RESPAWN_MINUTES[0]*60000);
const restored=createResourceLifecycle(JSON.parse(JSON.stringify(state)),{now:()=>now});
const same={...tree,hp:40,dead:false,mesh:{visible:true}};
restored.spawn(same);
assert.equal(same.dead,true,'destroyed state must survive a chunk reload');
now=until+1200;
restored.update([same],()=>false);
assert.equal(same.dead,true,'overlapped node must not respawn');
let callbacks=0;
restored.update([same],()=>true,()=>callbacks++);
assert.equal(same.dead,false);
assert.equal(same.hp,40);
assert.equal(callbacks,1);
assert.equal(Object.keys(restored.exhausted).length,0);
console.log('Partial regeneration, long respawn, overlap safety and persistence verified');
