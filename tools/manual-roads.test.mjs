import assert from 'node:assert/strict';
import {createRoadNetwork} from '../src/road-network.js';

const state={roads:{}},roads=createRoadNetwork(state);
let rebuilt=0;
roads.setProbes({blocked:()=>false,invalidate:()=>rebuilt++});
assert.equal(roads.rebuild([{id:'a',x:50,z:50}],{x:0,z:0}),false);
assert.equal(roads.plannedCount,0,'buildings must never automatically draw roads');
assert.equal(roads.built,0);
assert.equal(roads.claim('worker',{x:0,z:0}),null);
assert.ok(roads.paint({x:9,z:9},{x:24,z:9},'build','path')>=5);
assert.ok(roads.plannedCount>=5,'player drawn route should produce tasks');
assert.equal(roads.built,0,'blueprint must not instantly construct');
let job=roads.claim('worker',{x:9,z:9});
assert.equal(job.mode,'build');
assert.equal(roads.work('worker',job,15),'working');
assert.equal(roads.levelAt(job.x,job.z),0,'slow construction must remain pending');
assert.equal(roads.work('worker',job,17),'done');
assert.equal(roads.levelAt(job.x,job.z),1);
assert.equal(roads.speedAt(job.x,job.z),1.2);
const target={x:job.x,z:job.z};
roads.paint(target,target,'build','road');
assert.equal(roads.levelAt(target.x,target.z),1,'upgrades require employee time');
job=roads.claim('worker',target);
assert.equal(job.mode,'build');
assert.equal(roads.work('worker',job,45),'working');
assert.equal(roads.work('worker',job,1),'done');
assert.equal(roads.levelAt(target.x,target.z),2);
assert.equal(roads.speedAt(target.x,target.z),1.5);
for(let t=0;t<100000;t+=120)roads.update(t);
assert.equal(roads.levelAt(target.x,target.z),2,'roads never decay or auto-demolish');
roads.rebuild([], {x:0,z:0});
assert.equal(roads.levelAt(target.x,target.z),2,'removing a building does not change roads');
roads.paint(target,target,'demolish');
job=roads.claim('worker',target);
assert.equal(job.mode,'demolish');
assert.equal(roads.work('worker',job,25),'working');
assert.equal(roads.levelAt(target.x,target.z),2);
assert.equal(roads.work('worker',job,1),'done');
assert.equal(roads.levelAt(target.x,target.z),0);
assert.ok(rebuilt>=3);
const draft={x:35,z:35};
roads.paint(draft,draft,'build','road');
roads.paint(draft,draft,'demolish');
assert.equal(roads.levelAt(draft.x,draft.z),0);
assert.equal(roads.data[roads.point('11,11')],undefined);
assert.ok(!Object.values(roads.data).some(x=>x.goal==='demolish'&&x.l===0));
const copy=structuredClone(state);
const loaded=createRoadNetwork(copy);
assert.equal(loaded.levelAt(target.x,target.z),0);
assert.ok(loaded.plannedCount>0,'other queued blueprint tiles survive reload');
const filtered=createRoadNetwork({roads:{}});
filtered.setProbes({blocked:(x,z)=>x>5});
assert.equal(filtered.paint({x:10,z:10},{x:10,z:10},'build','road'),0,'solid terrain cannot be painted');
console.log('Manually drawn roads, slow work, upgrades, demolition, persistence and no-automation verified');